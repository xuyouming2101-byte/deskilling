create extension if not exists pgcrypto;

create table if not exists public.videos (
  video_id text primary key,
  bucket text not null,
  file_path text not null,
  has_lesion boolean not null default false,
  lesion_onset_sec numeric(10, 3),
  is_test boolean not null default true,
  session_pool integer check (session_pool between 1 and 3),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.videos
  add column if not exists has_lesion boolean not null default false,
  add column if not exists lesion_onset_sec numeric(10, 3),
  add column if not exists is_test boolean not null default true,
  add column if not exists session_pool integer;

create index if not exists videos_study_mode_pool_idx
  on public.videos (is_test, session_pool, video_id);

create table if not exists public.assessment_queue (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  session_number integer not null check (session_number between 1 and 3),
  video_id text not null references public.videos (video_id),
  video_order integer not null check (video_order >= 1),
  created_at timestamptz not null default now()
);

create unique index if not exists assessment_queue_session_order_idx
  on public.assessment_queue (participant_id, session_number, video_order);

create unique index if not exists assessment_queue_session_video_idx
  on public.assessment_queue (participant_id, session_number, video_id);

create table if not exists public.responses (
  id bigint generated by default as identity primary key,
  participant_id text not null,
  session_number integer not null check (session_number between 1 and 3),
  video_id text not null references public.videos (video_id),
  video_order integer not null check (video_order >= 1),
  answer text not null check (answer in ('yes', 'no')),
  correct boolean not null,
  response_type text not null check (
    response_type in ('lesion_detected', 'no_lesion_detected')
  ),
  response_time_ms integer not null check (response_time_ms >= 0),
  video_time_at_click numeric(10, 3),
  detection_latency_ms integer,
  video_completed boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.responses
  add column if not exists participant_id text,
  add column if not exists session_number integer,
  add column if not exists video_order integer,
  add column if not exists correct boolean,
  add column if not exists response_type text,
  add column if not exists video_time_at_click numeric(10, 3),
  add column if not exists detection_latency_ms integer,
  add column if not exists video_completed boolean not null default false;

create index if not exists responses_participant_session_order_idx
  on public.responses (participant_id, session_number, video_order);

create unique index if not exists responses_unique_trial
  on public.responses (participant_id, session_number, video_id, video_order);

