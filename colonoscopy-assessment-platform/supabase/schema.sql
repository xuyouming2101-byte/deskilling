  on public.assessment_queue;

create policy "Allow anonymous assessment queue lookup"
  on public.assessment_queue
  for select
  to anon
  using (true);

drop policy if exists "Allow anonymous assessment queue inserts"
  on public.assessment_queue;

create policy "Allow anonymous assessment queue inserts"
  on public.assessment_queue
  for insert
  to anon
  with check (
    length(trim(participant_id)) > 0
    and session_number between 1 and 3
    and video_order >= 1
    and exists (
      select 1
      from public.videos v
      where v.video_id = public.assessment_queue.video_id
    )
  );

drop policy if exists "Allow anonymous response inserts"
  on public.responses;

create policy "Allow anonymous response inserts"
  on public.responses
  for insert
  to anon
  with check (
    length(trim(participant_id)) > 0
    and session_number between 1 and 3
    and video_order >= 1
    and answer in ('yes', 'no')
    and correct is not null
    and response_type in ('lesion_detected', 'no_lesion_detected')
    and response_time_ms >= 0
    and video_time_at_click is not null
    and video_time_at_click >= 0
    and video_completed is not null
    and exists (
      select 1
      from public.videos v
      where v.video_id = public.responses.video_id
    )
  );

create or replace function public.get_next_video_order(
  p_participant_id text,
  p_session_number integer
)
returns integer
language sql
security definer
set search_path = public
as $$
  with queued as (
    select q.video_id, q.video_order
    from public.assessment_queue q
    where q.participant_id = p_participant_id
      and q.session_number = p_session_number
  )
  select coalesce(
    (
      select min(q.video_order)
      from queued q
      where not exists (
        select 1
        from public.responses r
        where r.participant_id = p_participant_id
          and r.session_number = p_session_number
          and r.video_id = q.video_id
          and r.video_order = q.video_order
      )
    ),
    (
      select count(*)::integer + 1
      from queued
    )
  );
$$;

grant execute on function public.get_next_video_order(text, integer) to anon;

